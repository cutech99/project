-- 개인 DB에서만 실행. RESERVATION과 RESERVATION_LANE이 모두 없는 경우 전용.
-- MEMBER(MEMBER_ID NUMBER PK), LANE(LANE_ID NUMBER PK,LANE_NO,STATUS)는 1번 정의 필요.
-- 1번 전체 스크립트는 이미 예약 테이블을 생성하므로 그 경우 이 파일 대신 02 사용.
-- DDL은 암묵적 COMMIT: 미완료 DML 없는 별도 세션에서 실행.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM user_tables WHERE table_name IN ('RESERVATION','RESERVATION_LANE');
 IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20001,'기존 예약 테이블 존재: CREATE 중단, 02 경로 확인'); END IF;
END;
/
CREATE TABLE RESERVATION (
 RESERVATION_ID NUMBER NOT NULL,
 MEMBER_ID NUMBER NOT NULL,
 RES_DATE DATE NOT NULL,
 STATUS VARCHAR2(20) DEFAULT 'RESERVED' NOT NULL,
 CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
 START_TIME DATE NOT NULL,
 END_TIME DATE NOT NULL,
 PERSON_COUNT NUMBER NOT NULL,
 CONSTRAINT PK_RESERVATION PRIMARY KEY(RESERVATION_ID),
 CONSTRAINT FK_RES_MEMBER FOREIGN KEY(MEMBER_ID) REFERENCES MEMBER(MEMBER_ID),
 CONSTRAINT CK_R2_PERSON CHECK(PERSON_COUNT >= 1 AND PERSON_COUNT = TRUNC(PERSON_COUNT)),
 CONSTRAINT CK_R2_TIME CHECK(END_TIME > START_TIME AND END_TIME <= START_TIME + 2/24),
 CONSTRAINT CK_R2_DATE CHECK(RES_DATE = START_TIME)
);
CREATE TABLE RESERVATION_LANE (
 RESERVATION_ID NUMBER NOT NULL,
 LANE_ID NUMBER NOT NULL,
 CONSTRAINT PK_RES_LANE PRIMARY KEY(RESERVATION_ID,LANE_ID),
 CONSTRAINT FK_RL_RES FOREIGN KEY(RESERVATION_ID) REFERENCES RESERVATION(RESERVATION_ID),
 CONSTRAINT FK_RL_LANE FOREIGN KEY(LANE_ID) REFERENCES LANE(LANE_ID)
);
-- 기존 시퀀스를 변경하지 않음. 새 테이블이므로 없는 경우에만 생성.
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM user_sequences WHERE sequence_name='SEQ_RESERVATION_ID';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_RESERVATION_ID START WITH 1 INCREMENT BY 1 NOCACHE'; END IF;
END;
/
